/**
 * Writes src/lib/icons/sprite.ts: the icons every property card repeats, as
 * symbol data for one SVG sprite per page instead of one inline SVG per card.
 *
 * A listing page carried 199 inline icons, 137 kB of its 697 kB HTML, for
 * 24 cards (measured 2026-09-30), and each one was a client component the
 * browser hydrated. With the sprite a card icon is a 90-byte `<use>`.
 *
 * Bodies come from bundle.ts, so run build-icon-bundle.mjs first when adding
 * an icon here. Run: node scripts/build-icon-sprite.mjs
 */
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const BUNDLE = "src/lib/icons/bundle.ts";
const OUT = "src/lib/icons/sprite.ts";
// The viewBoxes alone, for SpriteIcon: it ships to the browser inside every
// client component that draws a card, and the symbol bodies are only needed
// by the server-rendered sprite.
const OUT_VIEWBOX = "src/lib/icons/spriteViewBoxes.ts";
// Every icon the code names statically (18.10: `Icon` everywhere became
// `SpriteIcon`, so a page's hundred-odd icons stop being client components
// the browser hydrates one by one). Icons chosen in the CMS still go through
// `Icon` by way of SpriteIcon's fallback. Regenerate the list with:
//   grep -rhoE "icon=[\"'][a-z0-9-]+:[a-z0-9-]+[\"']" src | sed -E "s/icon=[\"']//;s/[\"']$//" | sort -u
const ICONS = [
  "lineicons:arrow-all-direction",
  "ph:arrow-left",
  "ph:arrow-right",
  "ph:arrow-square-out",
  "ph:arrows-left-right",
  "ph:buildings",
  "ph:calendar-blank",
  "ph:caret-down",
  "ph:caret-left",
  "ph:caret-right",
  "ph:chart-bar",
  "ph:chat-circle-dots-fill",
  "ph:check",
  "ph:circle-notch",
  "ph:clock",
  "ph:crane-tower-fill",
  "ph:envelope-simple",
  "ph:eye",
  "ph:globe-simple",
  "ph:fire-fill",
  "ph:heart",
  "ph:heart-fill",
  "ph:house-simple-fill",
  "ph:image",
  "ph:list",
  "ph:list-magnifying-glass",
  "ph:magnifying-glass",
  "ph:magnifying-glass-bold",
  "ph:map-pin",
  "ph:map-pin-fill",
  "ph:moon",
  "ph:paper-plane-tilt",
  "ph:phone-call-fill",
  "ph:play-circle",
  "ph:plus",
  "ph:question",
  "ph:sliders-horizontal",
  "ph:sort-ascending",
  "ph:sparkle",
  "ph:square",
  "ph:squares-four",
  "ph:star-fill",
  "ph:sun",
  "ph:table",
  "ph:tag-fill",
  "ph:telegram-logo",
  "ph:trash",
  "ph:users",
  "ph:whatsapp-logo",
  "ph:x",
  "solar:alt-arrow-left-linear",
  "solar:alt-arrow-right-linear",
  "solar:bath-linear",
  "solar:bed-linear",
  "solar:map-linear",
  "solar:maximize-square-minimalistic-linear",
];

const text = readFileSync(BUNDLE, "utf8");
const match = /const collections = (\[[\s\S]*?\]);\r?\n/.exec(text);
if (!match) throw new Error(`no collections literal in ${BUNDLE}`);
const collections = JSON.parse(match[1]);

const out = {};
for (const name of ICONS) {
  const [prefix, icon] = name.split(":");
  const collection = collections.find((c) => c.prefix === prefix);
  const alias = collection?.aliases?.[icon];
  const data = collection?.icons?.[icon] ?? (alias && collection.icons[alias.parent]);
  if (!data) throw new Error(`${name} is not in ${BUNDLE}; run scripts/build-icon-bundle.mjs first`);
  out[name] = {
    body: data.body,
    width: data.width ?? collection.width ?? 16,
    height: data.height ?? collection.height ?? 16,
    left: data.left ?? 0,
    top: data.top ?? 0,
  };
}

const header = [
  "// GENERATED by scripts/build-icon-sprite.mjs — do not edit by hand.",
  "//",
  "// Symbol data for the icons every property card repeats; see IconSprite and",
  "// SpriteIcon in components/shared. Re-run the script after changing the list.",
  "",
  "export type SpriteIconData = { body: string; width: number; height: number; left: number; top: number };",
  "",
].join("\n");
const footer = [
  "",
  '/** The id the page sprite gives an icon\'s symbol; "solar:bed-linear" → "i-solar-bed-linear". */',
  "export function spriteSymbolId(icon: string): string {",
  '  return `i-${icon.replace(":", "-")}`;',
  "}",
  "",
].join("\n");

writeFileSync(OUT, `${header}export const SPRITE_ICONS: Record<string, SpriteIconData> = ${JSON.stringify(out)};\n${footer}`);

// The sprite itself is one static SVG file, fetched once and cached, rather
// than symbols inlined into every document: inlined, 55 symbols were 24 KB in
// the HTML and the same again in the RSC payload of every page (18.10). The
// file name carries a content hash, so the header rule in next.config.ts can
// cache it for a year; a change in the icon list writes a new file.
const symbolId = (name) => `i-${name.replace(":", "-")}`;
const svg =
  '<svg xmlns="http://www.w3.org/2000/svg">' +
  Object.entries(out)
    .map(([name, d]) => `<symbol id="${symbolId(name)}" viewBox="${d.left} ${d.top} ${d.width} ${d.height}">${d.body}</symbol>`)
    .join("") +
  "</svg>";
const hash = createHash("sha256").update(svg).digest("hex").slice(0, 10);
const spriteDir = "public/icons";
mkdirSync(spriteDir, { recursive: true });
for (const old of readdirSync(spriteDir)) if (/^sprite\.[0-9a-f]+\.svg$/.test(old)) rmSync(`${spriteDir}/${old}`);
const spriteUrl = `/icons/sprite.${hash}.svg`;
writeFileSync(`public${spriteUrl}`, svg);

const viewBoxes = Object.fromEntries(
  Object.entries(out).map(([name, d]) => [name, `${d.left} ${d.top} ${d.width} ${d.height}`]),
);
writeFileSync(
  OUT_VIEWBOX,
  [
    "// GENERATED by scripts/build-icon-sprite.mjs — do not edit by hand.",
    "//",
    "// The viewBox of every icon in the sprite (lib/icons/sprite), without the",
    "// symbol bodies: SpriteIcon needs only this, and it ships to the browser.",
    "",
    `/** The static sprite file SpriteIcon's <use> points at; the hash is the file's content. */`,
    `export const SPRITE_URL = ${JSON.stringify(spriteUrl)};`,
    "",
    `export const SPRITE_VIEWBOXES: Record<string, string> = ${JSON.stringify(viewBoxes)};`,
    "",
  ].join("\n"),
);
console.log(`${OUT}: ${ICONS.length} icons; public${spriteUrl} (${svg.length} bytes)`);
