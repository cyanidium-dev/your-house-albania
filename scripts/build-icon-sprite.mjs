/**
 * Writes src/lib/icons/sprite.ts: the icons every property card repeats, as
 * symbol data for one SVG sprite per page instead of one inline SVG per card.
 *
 * A listing page carried 199 inline icons, 137 kB of its 697 kB HTML, for
 * 24 cards (measured 2026-09-30), and each one was a client component the
 * browser hydrated. With the sprite a card icon is a 90-byte `<use>`.
 *
 * Bodies come from bundle.ts, so run build-icon-bundle.mjs first when adding
 * an icon here. Run: node scripts/build-icon-sprite.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const BUNDLE = "src/lib/icons/bundle.ts";
const OUT = "src/lib/icons/sprite.ts";
const ICONS = [
  "solar:bed-linear",
  "solar:bath-linear",
  "lineicons:arrow-all-direction",
  "solar:map-linear",
  "solar:alt-arrow-left-linear",
  "solar:alt-arrow-right-linear",
  "solar:maximize-square-minimalistic-linear",
  "ph:star-fill",
  "ph:fire-fill",
  "ph:tag-fill",
  "ph:crane-tower-fill",
];

const text = readFileSync(BUNDLE, "utf8");
const match = /const collections = (\[[\s\S]*?\]);\r?\n/.exec(text);
if (!match) throw new Error(`no collections literal in ${BUNDLE}`);
const collections = JSON.parse(match[1]);

const out = {};
for (const name of ICONS) {
  const [prefix, icon] = name.split(":");
  const collection = collections.find((c) => c.prefix === prefix);
  const alias = collection?.aliases?.[icon];
  const data = collection?.icons?.[icon] ?? (alias && collection.icons[alias.parent]);
  if (!data) throw new Error(`${name} is not in ${BUNDLE}; run scripts/build-icon-bundle.mjs first`);
  out[name] = {
    body: data.body,
    width: data.width ?? collection.width ?? 16,
    height: data.height ?? collection.height ?? 16,
    left: data.left ?? 0,
    top: data.top ?? 0,
  };
}

const header = [
  "// GENERATED by scripts/build-icon-sprite.mjs — do not edit by hand.",
  "//",
  "// Symbol data for the icons every property card repeats; see IconSprite and",
  "// SpriteIcon in components/shared. Re-run the script after changing the list.",
  "",
  "export type SpriteIconData = { body: string; width: number; height: number; left: number; top: number };",
  "",
].join("\n");
const footer = [
  "",
  '/** The id the page sprite gives an icon\'s symbol; "solar:bed-linear" → "i-solar-bed-linear". */',
  "export function spriteSymbolId(icon: string): string {",
  '  return `i-${icon.replace(":", "-")}`;',
  "}",
  "",
].join("\n");

writeFileSync(OUT, `${header}export const SPRITE_ICONS: Record<string, SpriteIconData> = ${JSON.stringify(out)};\n${footer}`);
console.log(`${OUT}: ${ICONS.length} icons`);
